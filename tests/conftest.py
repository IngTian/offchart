@pytest.fixture
def nasdaq_consolidated(tff_fut) -> pd.DataFrame:
    """20974+ across the 2023-05-02 re-basing, date-sorted. 846 reports.

    The series a percentile must NOT be computed over in one piece: levels
    before and after the break differ by 5.17x for units, not positioning.
    """
    df = tff_fut[tff_fut["market_code"].astype(str) == NASDAQ_CONSOLIDATED]
