"""The documentation is layered, so the layers have to actually connect.

The README is the summary and `docs/` holds the specifics, which only works if the
pointers between them resolve. A dead relative link is invisible to every other check
in this repo -- the suite reads SQL and dashboards, not prose -- and it is the exact
kind of rot that a restructure introduces, because the restructure is when every path
changes at once.

It found nothing on its first run, which is the honest state to record: these tests
are a ratchet against the next restructure rather than a repair of this one.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
DOCS = sorted((ROOT / "docs").glob("*.md"))
MARKDOWN = [ROOT / "README.md", *DOCS]

#: `[text](target)`. Only relative targets are checked -- an http link's liveness is
#: not this repo's business and would make the suite need network.
LINK = re.compile(r"\[[^\]]+\]\(([^)]+)\)")


def test_there_is_a_docs_directory_with_the_layers_in_it() -> None:
    """The README names each of these, so their absence would be a dead pointer."""
    assert {p.name for p in DOCS} == {
        "data-notes.md", "grafana.md", "internals.md", "licensing.md", "querying.md"
    }, f"docs/ holds {[p.name for p in DOCS]} -- update the README's pointer table"


@pytest.mark.parametrize("path", MARKDOWN, ids=lambda p: p.name)
def test_every_relative_link_resolves(path: Path) -> None:
    broken = []
    for target in LINK.findall(path.read_text()):
        if target.startswith(("http://", "https://", "#", "mailto:")):
            continue
        # Strip an anchor: `querying.md#column-conventions` points at a file.
        resolved = (path.parent / target.split("#")[0]).resolve()
        if not resolved.exists():
            broken.append(target)
    assert not broken, f"{path.name} links to missing paths: {broken}"


@pytest.mark.parametrize("path", MARKDOWN, ids=lambda p: p.name)
def test_every_doc_opens_with_a_single_h1(path: Path) -> None:
    """One H1 per file, and it is the first non-blank line.

    Not style policing: the H1 is what the README's pointer table promises each file
    is about, so a file that opens with a section heading instead has lost its subject.
    """
    lines = [ln for ln in path.read_text().splitlines() if ln.strip()]
    assert lines and lines[0].startswith("# "), (
        f"{path.name} does not open with an H1"
    )
    assert sum(1 for ln in lines if ln.startswith("# ")) == 1, (
        f"{path.name} has more than one H1"
    )


def test_the_readme_stays_a_summary() -> None:
    """A soft ceiling, and the reason is the state this restructure undid.

    The README reached 617 lines doing five jobs at once, which put the section that
    stops a reader misusing every number at line 513 -- past where anyone reads. The
    limit is generous; the point is that the next 400-line addition goes in docs/ and
    gets a pointer, rather than being appended here because that is where the file
    already was.
    """
    n = len((ROOT / "README.md").read_text().splitlines())
    assert n < 320, (
        f"README.md is {n} lines. Move the reference material into docs/ and leave a "
        "pointer in the 'Where to look for things' table."
    )


def test_the_generated_table_says_it_is_generated() -> None:
    """The inventory table's counts have been wrong three times.

    `make readme-table` regenerates them, and the marker is what tells the next reader
    to run it instead of hand-editing a row. If the marker goes, the drift comes back.
    """
    text = (ROOT / "README.md").read_text()
    assert "make readme-table" in text
    assert "generated by `make readme-table`" in text, (
        "the inventory table lost its do-not-hand-edit marker"
    )
